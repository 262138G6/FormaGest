
package com.curso.formagest.model;

import com.curso.formagest.enums.EstadoSolicitud;
import com.curso.formagest.enums.SituacionLaboral;
import jakarta.persistence.*;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.LocalDate;

/**
 * Represents a student's application for a course edition.
 *
 * Maps to the "solicitud" table in PostgreSQL.
 * Each student can submit only one application per edition.
 */
@Entity
@Table(
        name = "solicitud",
        uniqueConstraints = {
                @UniqueConstraint(
                        name = "uq_solicitud_alumno_edicion",
                        columnNames = {"alumno_id", "edicion_id"}
                )
        }
)
@Getter
@Setter
@NoArgsConstructor
public class Solicitud {

    /**
     * Unique identifier generated by PostgreSQL.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Student submitting the application.
     */
    @NotNull(message = "El alumno es obligatorio")
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "alumno_id", nullable = false)
    private Alumno alumno;

    /**
     * Course edition requested by the student.
     */
    @NotNull(message = "La edición es obligatoria")
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "edicion_id", nullable = false)
    private Edicion edicion;

    /**
     * Date when the application was submitted.
     */
    @NotNull(message = "La fecha de solicitud es obligatoria")
    @Column(name = "fecha_solicitud", nullable = false)
    private LocalDate fechaSolicitud;

    /**
     * Employment status of the applicant.
     */
    @NotNull(message = "La situación laboral es obligatoria")
    @Enumerated(EnumType.STRING)
    @Column(name = "situacion_laboral", nullable = false, length = 20)
    private SituacionLaboral situacionLaboral;

    /**
     * Current status of the application.
     */
    @NotNull(message = "El estado de la solicitud es obligatorio")
    @Enumerated(EnumType.STRING)
    @Column(name = "estado", nullable = false, length = 20)
    private EstadoSolicitud estado;

    /**
     * Optional observations about the application.
     */
    @Size(max = 255, message = "Las observaciones no pueden superar 255 caracteres")
    @Column(name = "observaciones", length = 255)
    private String observaciones;

    /**
     * Initializes default values before inserting a new application.
     */
    @PrePersist
    public void prePersist() {

        if (fechaSolicitud == null) {
            fechaSolicitud = LocalDate.now();
        }

        if (estado == null) {
            estado = EstadoSolicitud.PENDIENTE;
        }
    }
}
