
package com.curso.formagest.controller;

import com.curso.formagest.model.Alumno;
import com.curso.formagest.repository.AlumnoRepository;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

/**
 * REST controller for managing students in FormaGest.
 *
 * Provides HTTP endpoints to perform CRUD operations
 * on student records stored in PostgreSQL.
 *
 * Base endpoint: /api/alumnos
 */
@RestController
@RequestMapping("/api/alumnos")
@RequiredArgsConstructor
public class AlumnoController {

    /**
     * Repository used to access and manage student records.
     * Injected through the constructor generated by Lombok.
     */
    private final AlumnoRepository alumnoRepository;

    /**
     * Retrieves all students registered in FormaGest.
     *
     * HTTP method: GET
     * Endpoint: /api/alumnos
     *
     * @return a list of students, or an empty list if none exist.
     */
    @GetMapping
    public List<Alumno> listarAlumnos() {
        return alumnoRepository.findAll();
    }

    /**
     * Retrieves a student by their unique identifier.
     *
     * HTTP method: GET
     * Endpoint: /api/alumnos/{id}
     *
     * @param id the identifier of the student.
     * @return HTTP 200 with the student if found,
     *         or HTTP 404 if the student does not exist.
     */
    @GetMapping("/{id}")
    public ResponseEntity<Alumno> obtenerAlumno(@PathVariable Long id) {

        return alumnoRepository.findById(id)
                .map(ResponseEntity::ok)
                .orElseGet(() -> ResponseEntity.notFound().build());
    }

    /**
     * Creates a new student in the database.
     *
     * HTTP method: POST
     * Endpoint: /api/alumnos
     *
     * Validates the student data before saving.
     * The identifier is generated automatically by PostgreSQL.
     *
     * @param alumno the validated student data.
     * @return HTTP 201 with the newly created student.
     */
    @PostMapping
    public ResponseEntity<Alumno> crearAlumno(
            @Valid @RequestBody Alumno alumno) {

        // Ensures PostgreSQL generates a new identifier.
        alumno.setId(null);

        // Persists the new student in the database.
        Alumno nuevoAlumno = alumnoRepository.save(alumno);

        return ResponseEntity
                .status(HttpStatus.CREATED)
                .body(nuevoAlumno);
    }

    /**
     * Updates an existing student's information.
     *
     * HTTP method: PUT
     * Endpoint: /api/alumnos/{id}
     *
     * Validates the received data before updating the record.
     *
     * @param id the identifier of the student to update.
     * @param datos the validated student information.
     * @return HTTP 200 with the updated student,
     *         or HTTP 404 if the student does not exist.
     */
    @PutMapping("/{id}")
    public ResponseEntity<Alumno> actualizarAlumno(
            @PathVariable Long id,
            @Valid @RequestBody Alumno datos) {

        // Searches for the existing student.
        return alumnoRepository.findById(id)
                .map(alumno -> {

                    // Updates the student's information.
                    alumno.setNombre(datos.getNombre());
                    alumno.setApellidos(datos.getApellidos());
                    alumno.setEmail(datos.getEmail());
                    alumno.setTelefono(datos.getTelefono());

                    // Persists the updated student.
                    Alumno alumnoActualizado =
                            alumnoRepository.save(alumno);

                    return ResponseEntity.ok(alumnoActualizado);
                })
                .orElseGet(() -> ResponseEntity.notFound().build());
    }

    /**
     * Deletes a student by their unique identifier.
     *
     * HTTP method: DELETE
     * Endpoint: /api/alumnos/{id}
     *
     * Prevents deletion when related database records exist.
     *
     * @param id the identifier of the student to delete.
     * @return HTTP 204 if successfully deleted,
     *         HTTP 404 if the student does not exist,
     *         or HTTP 409 if related records prevent deletion.
     */
    @DeleteMapping("/{id}")
    public ResponseEntity<Void> eliminarAlumno(@PathVariable Long id) {

        // Checks whether the student exists.
        if (!alumnoRepository.existsById(id)) {
            return ResponseEntity.notFound().build();
        }

        try {
            // Deletes the student from PostgreSQL.
            alumnoRepository.deleteById(id);
            alumnoRepository.flush();

            return ResponseEntity.noContent().build();

        } catch (DataIntegrityViolationException e) {

            // Returns a conflict when related records prevent deletion.
            return ResponseEntity.status(HttpStatus.CONFLICT).build();
        }
    }
}
