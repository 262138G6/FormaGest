
-- ============================================================
-- FORMAGEST - DATABASE SCHEMA
-- ============================================================
-- Project: FormaGest - Academic Management System
-- Database: PostgreSQL 14+
-- Database name: formagest_db
-- File: 01_schema.sql
--
-- Description:
-- Creates the database structure required by FormaGest.
-- The schema manages training courses, course editions,
-- students, applications and enrollments.
--
-- Main relationships:
--   curso     1 ---- N edicion
--   alumno    1 ---- N solicitud
--   edicion   1 ---- N solicitud
--   solicitud 1 ---- 0..1 matricula
--
-- Local setup:
-- 1. Install PostgreSQL 14 or later.
-- 2. Create the database using pgAdmin or SQL:
--
--    CREATE DATABASE formagest_db WITH ENCODING 'UTF8';
--
-- 3. Connect to the formagest_db database.
-- 4. Execute this script using the pgAdmin Query Tool.
--
-- IMPORTANT:
-- This script is intended for initial database creation.
-- Do not execute it again against an existing schema.
-- It does not contain DROP TABLE statements.
-- ============================================================


-- ============================================================
-- DATABASE TRANSACTION
-- ============================================================
-- All schema creation statements are executed within a
-- single transaction.
--
-- If any statement fails, the transaction can be rolled
-- back without leaving a partially created schema.
-- ============================================================

BEGIN;

-- Eliminar las tablas en orden inverso de dependencias.
DROP TABLE IF EXISTS solicitud CASCADE;
DROP TABLE IF EXISTS edicion CASCADE;
DROP TABLE IF EXISTS alumno CASCADE;
DROP TABLE IF EXISTS curso CASCADE;

-- ============================================================
-- 1. COURSE TABLE
-- ============================================================
-- Stores the general information about training courses.
--
-- A course represents a training program independently
-- of its scheduled editions.
--
-- Each course can have multiple editions.
--
-- Fields:
--   id          Unique identifier generated automatically.
--   codigo      Unique business code assigned to the course.
--   nombre      Course name.
--   descripcion Optional description of the course.
--   horas       Total duration of the course in hours.
--   activo      Indicates whether the course is available.
--
-- Business rules:
--   - Course codes must be unique.
--   - Course duration must be greater than zero.
--   - New courses are active by default.
-- ============================================================

CREATE TABLE curso (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       codigo VARCHAR(20) NOT NULL UNIQUE,
                       nombre VARCHAR(150) NOT NULL,
                       descripcion VARCHAR(255) NOT NULL,
                       horas INTEGER NOT NULL CHECK (horas > 0),
                       activo BOOLEAN NOT NULL DEFAULT TRUE
);


-- ============================================================
-- 2. COURSE EDITION TABLE
-- ============================================================
-- Stores the scheduled editions of training courses.
--
-- Each edition belongs to one course and defines its
-- dates, available places, delivery modality and target
-- student groups.
--
-- A course can have several editions with different
-- dates and enrollment conditions.
--
-- Fields:
--   id                       Unique edition identifier.
--   curso_id                 Reference to the parent course.
--   fecha_inicio             Edition start date.
--   fecha_fin                Edition end date.
--   plazas                   Total number of available places.
--   modalidad                Training delivery modality.
--   colectivo_destino        Target employment group.
--   porcentaje_desempleados  Reserved percentage for
--                            unemployed students.
--   porcentaje_trabajadores  Reserved percentage for
--                            employed students.
--   flexibilizar_cupos       Allows administrative flexibility
--                            in the planned distribution.
--
-- Business rules:
--   - An edition must reference an existing course.
--   - The end date cannot precede the start date.
--   - The number of places must be greater than zero.
--   - Allowed modalities:
--       PRESENCIAL, ONLINE, MIXTA.
--   - Allowed target groups:
--       DESEMPLEADOS, TRABAJADORES, MIXTO.
--   - Each percentage must be between 0 and 100.
--   - Both percentages must add up to exactly 100.
--   - Enrollment quota flexibility is disabled by default.
--
-- Relationship:
--   curso (1) ---- (N) edicion
-- ============================================================

CREATE TABLE edicion (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         curso_id BIGINT NOT NULL,
                         fecha_inicio DATE NOT NULL,
                         fecha_fin DATE NOT NULL,
                         plazas INTEGER NOT NULL,
                         modalidad VARCHAR(20) NOT NULL,

    -- Prevents editions from referencing nonexistent courses.
                         CONSTRAINT fk_edicion_curso FOREIGN KEY (curso_id)
                             REFERENCES curso(id) ON DELETE RESTRICT,

    -- Ensures that the edition date range is valid.
                         CONSTRAINT chk_edicion_fechas
                             CHECK (fecha_fin >= fecha_inicio),

    -- Requires at least one available place.
                         CONSTRAINT chk_edicion_plazas
                             CHECK (plazas > 0),

    -- Restricts the allowed training modalities.
                         CONSTRAINT chk_edicion_modalidad
                             CHECK (modalidad IN ('PRESENCIAL', 'ONLINE', 'MIXTA'))
);


-- ============================================================
-- 3. STUDENT TABLE
-- ============================================================
-- Stores the personal and contact information of students.
--
-- Students are registered independently of their course
-- applications and enrollments.
--
-- A student can submit applications for multiple editions.
--
-- Fields:
--   id          Unique student identifier.
--   nombre      Student first name.
--   apellidos   Student last names.
--   email       Unique email address.
--   telefono    Optional contact phone number.
--
-- Business rules:
--   - First name and last names are mandatory.
--   - Email is mandatory and must be unique.
--   - Phone number is optional.
--
-- Relationship:
--   alumno (1) ---- (N) solicitud
-- ============================================================

CREATE TABLE alumno (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nombre VARCHAR(80) NOT NULL,
                        apellidos VARCHAR(120) NOT NULL,
                        email VARCHAR(150) NOT NULL UNIQUE,
                        telefono VARCHAR(20)
);


-- ============================================================
-- 4. COURSE APPLICATION TABLE
-- ============================================================
-- Stores student applications for specific course editions.
--
-- An application represents a student's request to
-- participate in a particular edition.
--
-- Applications can remain pending, be placed on a waiting
-- list, be admitted, rejected or canceled.
--
-- Fields:
--   id                  Unique application identifier.
--   alumno_id           Student submitting the application.
--   edicion_id          Requested course edition.
--   fecha_solicitud     Application submission date.
--   situacion_laboral   Employment status declared when
--                       the application was submitted.
--   estado              Current application status.
--   observaciones       Optional administrative notes.
--
-- Business rules:
--   - A student must already exist.
--   - The requested edition must already exist.
--   - A student cannot submit duplicate applications
--     for the same edition.
--   - Application date defaults to the current date.
--   - Employment status must be:
--       DESEMPLEADO or TRABAJADOR.
--   - Allowed application statuses:
--       PENDIENTE, RESERVA, ADMITIDA,
--       RECHAZADA, CANCELADA.
--   - New applications are pending by default.
--
-- Relationships:
--   alumno  (1) ---- (N) solicitud
--   edicion (1) ---- (N) solicitud
-- ============================================================

CREATE TABLE solicitud (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           alumno_id BIGINT NOT NULL,
                           edicion_id BIGINT NOT NULL,
                           fecha_solicitud DATE NOT NULL DEFAULT CURRENT_DATE,
                           situacion_laboral VARCHAR(20) NOT NULL,
                           estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
                           observaciones VARCHAR(255),

    -- Ensures that the applicant exists.
                           CONSTRAINT fk_solicitud_alumno FOREIGN KEY (alumno_id)
                               REFERENCES alumno(id) ON DELETE RESTRICT,

    -- Ensures that the requested edition exists.
                           CONSTRAINT fk_solicitud_edicion FOREIGN KEY (edicion_id)
                               REFERENCES edicion(id) ON DELETE RESTRICT,

    -- Prevents duplicate applications for the same edition.
                           CONSTRAINT uq_solicitud_alumno_edicion
                               UNIQUE (alumno_id, edicion_id),

    -- Restricts the allowed employment situations.
                           CONSTRAINT chk_solicitud_situacion
                               CHECK (situacion_laboral IN (
                                                            'DESEMPLEADO', 'TRABAJADOR'
                                   )),

    -- Restricts the allowed application statuses.
                           CONSTRAINT chk_solicitud_estado
                               CHECK (estado IN (
                                                 'PENDIENTE',
                                                 'RESERVA',
                                                 'ADMITIDA',
                                                 'RECHAZADA',
                                                 'CANCELADA'
                                   ))
);


-- ============================================================
-- 6. DATABASE INDEXES
-- ============================================================
-- Indexes improve the performance of frequently used
-- queries, joins and filtering operations.
--
-- Primary keys and UNIQUE constraints already create
-- their own supporting indexes in PostgreSQL.
--
-- The following indexes support common application queries.
-- ============================================================

-- Speeds up the retrieval of editions belonging to a course.
CREATE INDEX idx_edicion_curso
    ON edicion(curso_id);

-- Speeds up filtering applications by edition and status.
CREATE INDEX idx_solicitud_edicion_estado
    ON solicitud(edicion_id, estado);

-- Speeds up the retrieval of applications for a student.
CREATE INDEX idx_solicitud_alumno
    ON solicitud(alumno_id);


-- ============================================================
-- 7. DATABASE METADATA AND COMMENTS
-- ============================================================
-- PostgreSQL COMMENT statements store documentation
-- directly in the database catalog.
--
-- These comments can be inspected using PostgreSQL tools,
-- including pgAdmin.
-- ============================================================

-- Describes the purpose of the database.
COMMENT ON DATABASE formagest_db
    IS 'FormaGest - Sistema de Gestion Academica';

-- Preserves the student's employment status at application time.
COMMENT ON COLUMN solicitud.situacion_laboral
    IS 'Situacion declarada en el momento de la solicitud; se conserva para informes historicos';



-- ============================================================
-- 8. TRANSACTION COMMIT
-- ============================================================
-- Commits all database objects and metadata changes.
-- ============================================================

COMMIT;
